const trig = [], shuffle = [], windows = [];

function transformTables(bits) {
  for (let b = 0; b <= bits; b++) {
    if (trig[b]) continue;
    const n = 1 << b, sin = new Float64Array(n), cos = new Float64Array(n), sh = new Int32Array(n);
    for (let i = 0; i < n; i++) {
      const v = Math.PI * (4 * i + 1) / (4 * n);
      sin[i] = Math.sin(v);
      cos[i] = Math.cos(v);
      let x = i ^ (i >> 1), r = 0;
      for (let k = 0; k < b; k++, x >>= 1) r = (r << 1) | (x & 1);
      sh[i] = r;
    }
    trig[b] = [sin, cos];
    shuffle[b] = sh;
  }
  if (!windows[bits]) {
    const n = 1 << bits, mdct = new Float64Array(n), imdct = new Float64Array(n);
    for (let i = 0; i < n; i++) mdct[i] = (Math.sin(((i + 0.5) / n - 0.5) * Math.PI) + 1) * 0.5;
    for (let i = 0; i < n; i++) imdct[i] = mdct[i] / (mdct[n - 1 - i] * mdct[n - 1 - i] + mdct[i] * mdct[i]);
    windows[bits] = { mdct, imdct };
  }
}

// DCT-IV (LibAtrac9's fast algorithm; it is its own inverse up to scale).
function dct4(bits, input, output, tmp) {
  const size = 1 << bits, last = size - 1, half = size >> 1;
  let [sin, cos] = trig[bits];
  for (let i = 0; i < half; i++) {
    const i2 = i * 2, a = input[i2], b = input[last - i2];
    tmp[i2] = a * cos[i] + b * sin[i];
    tmp[i2 + 1] = a * sin[i] - b * cos[i];
  }
  const stages = bits - 1;
  for (let stage = 0; stage < stages; stage++) {
    const blocks = 1 << stage, sizeBits = stages - stage;
    const bsize = 1 << sizeBits, bhalf = bsize >> 1;
    [sin, cos] = trig[sizeBits - 1];
    for (let blk = 0; blk < blocks; blk++) {
      for (let i = 0; i < bhalf; i++) {
        const f = (blk * bsize + i) * 2, k = f + bsize;
        const a = tmp[f] - tmp[k], b = tmp[f + 1] - tmp[k + 1];
        tmp[f] += tmp[k];
        tmp[f + 1] += tmp[k + 1];
        tmp[k] = a * cos[i] + b * sin[i];
        tmp[k + 1] = a * sin[i] - b * cos[i];
      }
    }
  }
  const sh = shuffle[bits];
  for (let i = 0; i < size; i++) output[i] = tmp[sh[i]];
}


