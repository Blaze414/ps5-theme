/* The console decodes with Sony's own decoder, which minds things LibAtrac9
   and FFmpeg ignore. Versions 1.10-1.12 of this encoder wrote valid ATRAC9
   that the console played as ticks or silence: they left the unused end of
   each superframe as zeros, where Sony's files have 0x01 (confirmed on 13.42:
   the same audio data played once only those bytes changed). The encoder
   also writes only what the system file it replaces uses (its profile, see
   fitsProfile); every system ATRAC9 file on 13.42 (bgm_home, bgm_onboarding,
   bgm_onboarding_vr and the four sfx_*) stays inside one envelope:
   - bit allocation mode 3 (the only mode in those files): start unit 12-22,
     start value 0-11, boundary 0-15, as they use;
   - no more bands than the system file (13 on 13.42: 13.5 kHz at 48 kHz),
     no band extension;
   - precisions up to the system file's highest, and at most 7 (Sony's files
     use up to 7, once 8; never fine);
   - the LFE block coded as the system file codes it;
   - frames of at most 1.25 times the nominal frame size;
   - unused superframe space filled with the system file's byte (0x01).
   Within that, each superframe gets the allocation with the least
   quantization error that fits it (a Lagrangian search over its frames). */

