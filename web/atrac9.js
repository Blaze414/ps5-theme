function u32(b, o) { return (b[o] | b[o + 1] << 8 | b[o + 2] << 16 | b[o + 3] << 24) >>> 0; }
function u16(b, o) { return b[o] | b[o + 1] << 8; }
function hex(b, o, n) { let s = ""; for (let i = 0; i < n; i++) s += b[o + i].toString(16).padStart(2, "0"); return s; }

function readConfig(c) {
  if (c[0] !== 0xfe) fail("ATRAC9 config does not start with 0xFE");
  const sri = c[1] >> 4, cci = (c[1] >> 1) & 7;
  if (c[1] & 1) fail("ATRAC9 config validation bit is set");
  if (cci > 5) fail("unknown ATRAC9 channel layout");
  const frameBytes = ((c[2] << 3) | (c[3] >> 5)) + 1;
  const sfi = (c[3] >> 3) & 3;
  if (sfi & 1) fail("unsupported ATRAC9 superframe size");
  const blocks = CHANNEL_CONFIGS[cci];
  const power = FRAME_POWER[sri];
  return {
    bytes: Array.from(c.subarray(0, 4)), sri, cci, rate: SAMPLE_RATES[sri], high: sri > 7,
    blocks, channels: blocks.reduce((n, t) => n + (t === STEREO ? 2 : 1), 0),
    frameBytes, framesPerSuperframe: 1 << sfi, superframeBytes: frameBytes << sfi,
    power, frameSamples: 1 << power, superframeSamples: (1 << power) << sfi,
  };
}

// Parse an .at9 (RIFF WAVE, WAVE_FORMAT_EXTENSIBLE with the ATRAC9 subtype).
function parseFile(bytes) {
  const b = bytes instanceof Uint8Array ? bytes : new Uint8Array(bytes);
  if (b.length < 12 || hex(b, 0, 4) !== "52494646" || hex(b, 8, 4) !== "57415645") fail("not a RIFF WAVE file");
  const chunks = [];
  let fmt = null, fact = null, loop = null, data = null;
  for (let p = 12; p + 8 <= b.length;) {
    const id = String.fromCharCode(b[p], b[p + 1], b[p + 2], b[p + 3]), size = u32(b, p + 4);
    if (p + 8 + size > b.length) fail(`chunk ${id} runs past the end of the file`);
    const body = b.subarray(p + 8, p + 8 + size);
    chunks.push({ id, body });
    if (id === "fmt ") fmt = body;
    else if (id === "fact" && size >= 12) fact = [u32(body, 0), u32(body, 4), u32(body, 8)];
    else if (id === "smpl" && size >= 60 && u32(body, 28) >= 1) loop = [u32(body, 44), u32(body, 48)];
    else if (id === "data") data = { offset: p + 8, length: size };
    p += 8 + size + (size & 1);
  }
  if (!fmt || fmt.length < 52 || u16(fmt, 0) !== 0xfffe || hex(fmt, 24, 16) !== ATRAC9_GUID) fail("not an ATRAC9 file");
  if (!data) fail("no audio data");
  const config = readConfig(fmt.subarray(44, 48));
  if (u16(fmt, 2) !== config.channels) fail("channel count does not match the ATRAC9 config");
  if (u32(fmt, 4) !== config.rate) fail("sample rate does not match the ATRAC9 config");
  if (u16(fmt, 12) !== config.superframeBytes) fail("block size does not match the ATRAC9 config");
  if (data.length % config.superframeBytes) fail("audio data is not a whole number of superframes");
  return { bytes: b, chunks, fmt, fact, loop, data, config, superframes: data.length / config.superframeBytes };
}


/* ---- Bit reader / writer ------------------------------------------------ */

class Reader {
  constructor(bytes, start, end) { this.b = bytes; this.pos = start * 8; this.end = end * 8; }
  peek(n) {
    const p = this.pos, i = p >> 3, b = this.b;
    const w = (b[i] << 24 | b[i + 1] << 16 | b[i + 2] << 8 | b[i + 3]) << (p & 7);
    return w >>> (32 - n);
  }
  read(n) {
    if (!n) return 0;
    const v = this.peek(n);
    this.pos += n;
    if (this.pos > this.end) fail("frame runs past the end of its superframe");
    return v;
  }
  signed(n) { return signExtend(this.read(n), n); }
  huff(cb) {
    const s = cb.lookup[this.peek(cb.maxBits)];
    if (s < 0) fail("invalid Huffman code");
    this.pos += cb.bits[s];
    if (this.pos > this.end) fail("frame runs past the end of its superframe");
    return s;
  }
  align() { this.pos = (this.pos + 7) & ~7; }
}

class Writer {
  constructor(bytes, start) { this.b = bytes; this.pos = start * 8; }
  write(v, n) {
    for (let i = n - 1; i >= 0; i--, this.pos++) {
      if ((v >> i) & 1) this.b[this.pos >> 3] |= 0x80 >> (this.pos & 7);
    }
  }
  align() { this.pos = (this.pos + 7) & ~7; }
}


/* ---- Decoder ------------------------------------------------------------ */

function newChannel(index) {
  return {
    index, sf: new Int32Array(48), sfPrev: new Int32Array(48), prec: new Int32Array(48),
    fine: new Int32Array(48), set: new Uint8Array(48), q: new Int32Array(256), qf: new Int32Array(256),
    spectra: new Float64Array(256), prev: new Float64Array(256), pcm: new Float64Array(256),
    coded: 0, bexMode: 0, bexValues: [0, 0, 0, 0], rng: null,
  };
}

function newBlock(type) {
  return {
    type, channels: type === STEREO ? [newChannel(0), newChannel(1)] : [newChannel(0)],
    haveBands: false, bandCount: 0, units: 0, stereoUnits: 0, bexEnabled: 0, extUnit: 0, unitsPrev: 0,
    gradMode: 0, gradient: new Int32Array(49), boundary: 0, primary: 0, signs: new Int32Array(32), hasExt: 0,
  };
}

function makeGradient(blk, start, end, startValue, endValue) {
  if (start >= end || end > 31) fail("invalid bit allocation range");
  if (blk.boundary > blk.units) fail("invalid bit allocation boundary");
  fillGradient(blk.gradient, start, end, startValue, endValue, blk.units);
}

// The bit allocation gradient (shared by the decoder and the encoder).
function fillGradient(g, start, end, startValue, endValue, units) {
  const values = endValue - startValue;
  for (let i = 0; i < end; i++) g[i] = startValue;
  for (let i = end; i <= units; i++) g[i] = endValue;
  if (!values) return;
  const curve = CURVES[end - start - 1], scale = (Math.abs(values) - 1) / 31;
  for (let i = start; i < end; i++) {
    const step = Math.trunc(curve[i - start] * scale);
    g[i] = values > 0 ? startValue + 1 + step : startValue - 1 - step;
  }
}

function precisions(blk, ch) {
  const sf = ch.sf, n = blk.units, mask = new Int32Array(n + 1);
  if (blk.gradMode) {
    for (let i = 1; i < n; i++) {
      const d = sf[i] - sf[i - 1];
      if (d > 1) mask[i] += Math.min(d - 1, 5);
      else if (d < -1) mask[i - 1] += Math.min(-d - 1, 5);
    }
  }
  for (let i = 0; i < n; i++) {
    let p;
    if (blk.gradMode) {
      p = sf[i] + mask[i] - blk.gradient[i];
      if (p > 0) p = blk.gradMode === 1 ? p >> 1 : blk.gradMode === 2 ? (3 * p) >> 3 : p >> 2;
    } else {
      p = sf[i] - blk.gradient[i];
    }
    p = Math.max(p, 1) + (i < blk.boundary ? 1 : 0);
    if (p > 30) fail("precision out of range");
    ch.fine[i] = p > 15 ? p - 15 : 0;
    ch.prec[i] = Math.min(p, 15);
  }
}

function codebookSets(cfg, ch, units) {
  const sf = ch.sf, set = ch.set;
  set.fill(0);
  if (units <= 1 || cfg.high) return;
  const keep = sf[units];
  sf[units] = sf[units - 1];
  let avg = 0;
  if (units > 12) {
    for (let i = 0; i < 12; i++) avg += sf[i];
    avg = Math.trunc((avg + 6) / 12);
  }
  for (let i = 8; i < units; i++) {
    const lo = Math.min(sf[i - 1], sf[i + 1]);
    if (sf[i] - lo >= 3 || sf[i] - sf[i - 1] + sf[i] - sf[i + 1] >= 3) set[i] = 1;
  }
  for (let i = 12; i < units; i++) {
    if (set[i]) continue;
    const lo = Math.min(sf[i - 1], sf[i + 1]);
    if (sf[i] - lo >= 2 && sf[i] >= avg - (UNIT_START[i + 1] - UNIT_START[i] === 16 ? 1 : 0)) set[i] = 1;
  }
  sf[units] = keep;
}

function readScaleFactors(br, blk, ch, first) {
  const { sfUnsigned, sfSigned } = codebooks();
  const sf = ch.sf, n = blk.extUnit, mode = br.read(2);
  sf.fill(0);
  const deltaOffset = (weights, base, cb, count) => {
    sf[0] = br.read(cb.vb);
    for (let i = 1; i < count; i++) sf[i] = (sf[i - 1] + br.huff(cb)) & cb.mask;
    for (let i = 0; i < count; i++) sf[i] += base - (weights ? weights[i] : 0);
  };
  const distance = (baseline, baseLen) => {
    const cb = sfSigned[br.read(2) + 2], count = Math.min(n, baseLen);
    for (let i = 0; i < count; i++) sf[i] = baseline[i] + signExtend(br.huff(cb), cb.vb);
    for (let i = count; i < n; i++) sf[i] = br.read(5);
  };
  const offsetBaseline = (baseline, baseLen) => {
    const base = br.read(5) - 16, cb = sfUnsigned[br.read(2) + 1], count = Math.min(n, baseLen);
    deltaOffset(null, 0, cb, count);
    for (let i = 0; i < count; i++) sf[i] += base + baseline[i];
    for (let i = count; i < n; i++) sf[i] = br.read(5);
  };
  if (mode === 0) {
    const weights = SF_WEIGHTS[br.read(3)], base = br.read(5);
    deltaOffset(weights, base, sfUnsigned[br.read(2) + 3], n);
  } else if (ch.index === 0) {
    if (mode === 1) {
      const len = br.read(2) + 2, base = len < 5 ? br.read(5) : 0;
      for (let i = 0; i < n; i++) sf[i] = br.read(len) + base;
    } else {
      if (first) fail("scale factors refer to a previous frame in the first frame");
      if (mode === 2) distance(ch.sfPrev, blk.unitsPrev);
      else offsetBaseline(ch.sfPrev, blk.unitsPrev);
    }
  } else if (mode === 1) {
    distance(blk.channels[0].sf, n);
  } else if (mode === 2) {
    offsetBaseline(blk.channels[0].sf, n);
  } else {
    if (first) fail("scale factors refer to a previous frame in the first frame");
    distance(ch.sfPrev, blk.unitsPrev);
  }
  for (let i = 0; i < n; i++) if (sf[i] < 0 || sf[i] > 31) fail("scale factor out of range");
  ch.sfPrev.set(sf);
}

function readSpectra(br, cfg, ch) {
  const { spectrum } = codebooks();
  const maxHuff = cfg.high ? 1 : 7;
  ch.q.fill(0);
  ch.qf.fill(0);
  for (let i = 0; i < ch.coded; i++) {
    const start = UNIT_START[i], end = UNIT_START[i + 1], bits = ch.prec[i] + 1;
    if (bits <= maxHuff) {
      const cb = spectrum[ch.set[i]][bits][UNIT_BOOK[i]];
      if (!cb) fail("invalid spectrum codebook");
      for (let k = start; k < end; k += cb.vc) {
        let v = br.huff(cb);
        for (let j = 0; j < cb.vc; j++, v >>= cb.vb) ch.q[k + j] = signExtend(v & cb.mask, cb.vb);
      }
    } else {
      for (let k = start; k < end; k++) ch.q[k] = br.signed(bits);
    }
  }
  for (let i = 0; i < ch.coded; i++) {
    if (!ch.fine[i]) continue;
    for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) ch.qf[k] = br.signed(ch.fine[i] + 1);
  }
}

function readBex(br, blk) {
  let band = 0;
  if (blk.bexEnabled) {
    if (blk.units < 13 || blk.units > 20) fail("band extension with an invalid band count");
    band = BEX_GROUPS[blk.units - 13][2];
    if (blk.type === STEREO) {
      const m = br.read(2);
      blk.channels[1].bexMode = band > 2 ? m : 4;
    } else {
      br.read(1);
    }
  }
  blk.hasExt = br.read(1);
  if (!blk.hasExt) return;
  if (!blk.bexEnabled) {
    br.read(2);
    const len = br.read(5);
    for (let i = 0; i < len; i++) br.read(1);
    return;
  }
  const m = br.read(2);
  blk.channels[0].bexMode = band > 2 ? m : 4;
  const len = br.read(5);
  if (!len) return;
  const end = br.pos + len;
  for (const ch of blk.channels) {
    const lengths = BEX_LENGTHS[ch.bexMode][band];
    for (let i = 0; i < BEX_COUNTS[ch.bexMode][band]; i++) ch.bexValues[i] = br.read(lengths[i]);
  }
  if (br.pos > end) fail("band extension data is longer than declared");
}

function unpackBlock(br, cfg, blk, frameIndex) {
  const first = !br.read(1), reuse = br.read(1);
  if (first !== (frameIndex === 0)) fail("superframe flag does not match the frame position");
  if (blk.type === LFE) {
    const ch = blk.channels[0];
    blk.units = 2;
    ch.coded = 2;
    ch.sf.fill(0);
    ch.sf[0] = br.read(5);
    ch.sf[1] = br.read(5);
    const p = reuse ? 8 : 4;
    blk.lfeReuse = reuse;
    ch.prec[0] = ch.prec[1] = p;
    ch.fine[0] = ch.fine[1] = 0;
    ch.q.fill(0);
    ch.qf.fill(0);
    for (let k = 0; k < 4; k++) ch.q[k] = br.signed(p + 1);
    br.align();
    return;
  }
  if (first && reuse) fail("first frame of a superframe reuses band parameters");
  const minBands = cfg.high ? 1 : 3;
  if (!reuse) {
    blk.bandCount = br.read(4) + minBands;
    if (blk.bandCount > MAX_BANDS[cfg.sri]) fail("band count out of range");
    blk.units = BAND_UNITS[blk.bandCount];
    const stereoBand = blk.type === STEREO ? br.read(4) + minBands : blk.bandCount;
    if (stereoBand > blk.bandCount) fail("stereo band out of range");
    blk.stereoUnits = BAND_UNITS[stereoBand];
    blk.bexEnabled = br.read(1);
    if (blk.bexEnabled) {
      const ext = br.read(4) + minBands;
      if (ext < blk.bandCount || ext > (cfg.high ? 16 : 18)) fail("extension band out of range");
      blk.extUnit = BAND_UNITS[ext];
    } else {
      blk.extUnit = blk.units;
    }
    blk.haveBands = true;
  } else if (!blk.haveBands) {
    fail("block reuses band parameters it never had");
  }

  blk.gradMode = br.read(2);
  let start, end, startValue, endValue;
  if (blk.gradMode) {
    start = br.read(5); end = 31; startValue = br.read(5); endValue = 31;
  } else {
    start = br.read(6); end = br.read(6) + 1; startValue = br.read(5); endValue = br.read(5);
  }
  blk.boundary = br.read(4);
  makeGradient(blk, start, end, startValue, endValue);

  if (blk.type === STEREO) {
    blk.primary = br.read(1);
    const signs = br.read(1);
    blk.signs.fill(0);
    if (signs) for (let i = blk.stereoUnits; i < blk.units; i++) blk.signs[i] = br.read(1);
  } else {
    blk.primary = 0;
  }
  readBex(br, blk);

  for (const ch of blk.channels) {
    ch.coded = ch.index === blk.primary ? blk.units : blk.stereoUnits;
    readScaleFactors(br, blk, ch, first);
    precisions(blk, ch);
    codebookSets(cfg, ch, ch.coded);
    readSpectra(br, cfg, ch);
  }
  blk.unitsPrev = blk.bexEnabled ? blk.extUnit : blk.units;
  br.align();
}

function rngNext(r) {
  const t = (r[3] ^ (r[3] << 5)) & 0xffff;
  r[3] = r[2]; r[2] = r[1]; r[1] = r[0];
  r[0] = (t ^ r[0] ^ ((t ^ (r[0] >> 5)) >> 4)) & 0xffff;
  return r[0];
}

function bandExtension(blk, ch) {
  const sf = ch.sf, s = ch.spectra, v = ch.bexValues;
  const aUnit = blk.units, [bUnit, cUnit, bands] = BEX_GROUPS[blk.units - 13];
  const total = Math.max(cUnit, 22), bexUnits = total - aUnit;
  const aBin = UNIT_START[aUnit], bBin = UNIT_START[bUnit], cBin = UNIT_START[cUnit], tBin = UNIT_START[total];
  for (let i = 0; i < bBin - aBin; i++) s[aBin + i] = s[aBin - i - 1];
  for (let i = 0; i < cBin - bBin; i++) s[bBin + i] = s[bBin - i - 1];
  for (let i = 0; i < tBin - cBin; i++) s[cBin + i] = s[cBin - i - 1];
  const noise = (index, count) => {
    if (!ch.rng) {
      const seed = (543 * (sf[8] + sf[12] + sf[15] + 1)) & 0xffff;
      const x = Math.imul(0x4d93, seed ^ (seed >> 14));
      ch.rng = [(3 - x) & 0xffff, (2 - x) & 0xffff, (1 - x) & 0xffff, (0 - x) & 0xffff];
    }
    for (let i = 0; i < count; i++) s[index + i] = rngNext(ch.rng) / 65535 * 2 - 1;
  };
  const scaleUnits = scales => {
    for (let i = aUnit; i < total; i++) {
      for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) s[k] *= scales[i - aUnit];
    }
  };
  const scales = [0, 0, 0, 0, 0, 0];
  switch (ch.bexMode) {
    case 0:
      if (bands === 3 || bands === 4) {
        const t = bands === 3 ? BEX_MODE0_3 : BEX_MODE0_4;
        scales[0] = t[0][v[0]]; scales[1] = t[1][v[0]]; scales[2] = t[2][v[1]];
        scales[3] = t[3][v[2]]; scales[4] = t[4][v[3]];
      } else if (bands === 5) {
        scales[0] = BEX_MODE0_5[0][v[0]]; scales[1] = BEX_MODE0_5[1][v[1]]; scales[2] = BEX_MODE0_5[2][v[1]];
      }
      scales[bexUnits - 1] = 2 ** (sf[aUnit] - 15);
      noise(UNIT_START[total - 1], UNIT_START[total] - UNIT_START[total - 1]);
      scaleUnits(scales);
      break;
    case 1:
      for (let i = aUnit; i < total; i++) scales[i - aUnit] = 2 ** (sf[i] - 15);
      noise(aBin, tBin - aBin);
      scaleUnits(scales);
      break;
    case 2:
      for (let i = aBin; i < bBin; i++) s[i] *= BEX_MODE2[v[0]];
      for (let i = bBin; i < cBin; i++) s[i] *= BEX_MODE2[v[1]];
      break;
    case 3: {
      const rate = 2 ** BEX_MODE3_RATE[v[1]];
      let scale = BEX_MODE3_INITIAL[v[0]];
      for (let i = aBin; i < tBin; i++) { scale *= rate; s[i] *= scale; }
      break;
    }
    case 4: {
      const m = BEX_MODE4[v[0]];
      for (let i = aBin; i < bBin; i++) s[i] *= 0.7079468 * m;
      for (let i = bBin; i < cBin; i++) s[i] *= 0.5011902 * m;
      for (let i = cBin; i < tBin; i++) s[i] *= 0.3548279 * m;
      break;
    }
  }
}

function imdct(cfg, ch, tmp) {
  const size = cfg.frameSamples, half = size >> 1, w = windows[cfg.power].imdct, d = tmp.out, prev = ch.prev;
  dct4(cfg.power, ch.spectra, d, tmp.work);
  for (let i = 0; i < half; i++) {
    ch.pcm[i] = w[i] * d[i + half] + prev[i];
    ch.pcm[i + half] = w[i + half] * -d[size - 1 - i] - prev[i + half];
    prev[i] = w[size - 1 - i] * -d[half - i - 1];
    prev[i + half] = w[half - i - 1] * d[i];
  }
}

function synthesize(cfg, blk, tmp) {
  for (const ch of blk.channels) {
    const sp = ch.spectra;
    sp.fill(0);
    for (let i = 0; i < ch.coded; i++) {
      const step = STEP[ch.prec[i]], fine = STEP_FINE[ch.fine[i]];
      for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) sp[k] = ch.q[k] * step + ch.qf[k] * fine;
    }
  }
  if (blk.type === STEREO && blk.stereoUnits < blk.units) {
    const src = blk.channels[blk.primary], dst = blk.channels[blk.primary ? 0 : 1];
    for (let i = blk.stereoUnits; i < blk.units; i++) {
      for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) dst.spectra[k] = blk.signs[i] ? -src.spectra[k] : src.spectra[k];
    }
  }
  for (const ch of blk.channels) {
    for (let i = 0; i < blk.units; i++) {
      const scale = 2 ** (ch.sf[i] - 15);
      for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) ch.spectra[k] *= scale;
    }
    if (blk.type !== LFE && blk.bexEnabled && blk.hasExt) bandExtension(blk, ch);
    imdct(cfg, ch, tmp);
  }
}

/* Which coding features a file uses. A replacement must stay within the
   system file's profile (see fitsProfile): the console decodes with Sony's
   decoder, which reads parts of the format Sony's encoder never writes
   differently from LibAtrac9 and FFmpeg. */
function newProfile() {
  return { modes: 0, maxBands: 0, maxPrecision: 0, fine: false, bex: false, lfeReuse: 0, maxFrame: 0, padding: new Set() };
}

function addToProfile(prof, blk) {
  if (blk.type === LFE) { prof.lfeReuse |= 1 << blk.lfeReuse; return; }
  prof.modes |= 1 << blk.gradMode;
  prof.maxBands = Math.max(prof.maxBands, blk.bandCount);
  prof.bex = prof.bex || !!blk.bexEnabled;
  for (const ch of blk.channels) {
    for (let i = 0; i < ch.coded; i++) {
      prof.maxPrecision = Math.max(prof.maxPrecision, ch.prec[i]);
      if (ch.fine[i]) prof.fine = true;
    }
  }
}

// Why `got` uses something `stock` never does, or "" if it does not.
function fitsProfile(got, stock, frameBytes) {
  const modes = m => [0, 1, 2, 3].filter(i => m & (1 << i)).join(", ");
  if (got.modes & ~stock.modes) return `uses bit allocation mode ${modes(got.modes & ~stock.modes)}, which the system sound never does`;
  if (got.maxBands > stock.maxBands) return `uses ${got.maxBands} bands; the system sound uses at most ${stock.maxBands}`;
  if (got.maxPrecision > stock.maxPrecision) return `uses precision ${got.maxPrecision}; the system sound uses at most ${stock.maxPrecision}`;
  if (got.fine && !stock.fine) return "uses fine precision, which the system sound never does";
  if (got.bex && !stock.bex) return "uses band extension, which the system sound never does";
  if (got.lfeReuse & ~stock.lfeReuse) return "codes the LFE channel differently from the system sound";
  const limit = Math.max(stock.maxFrame, Math.floor(frameBytes * FRAME_CAP));
  if (got.maxFrame > limit) return `has a ${got.maxFrame}-byte frame; the limit is ${limit}`;
  // Sony fills the unused end of a superframe with 0x01; its decoder minds.
  const pad = paddingByte(stock);
  for (const v of got.padding) if (v !== pad && !stock.padding.has(v)) return `fills unused space with 0x${hex2(v)} where the system sound uses 0x${hex2(pad)}`;
  return "";
}

const hex2 = v => v.toString(16).padStart(2, "0");

// The byte a file fills the unused end of its superframes with (Sony: 0x01).
function paddingByte(profile) {
  return profile.padding.size && !profile.padding.has(1) ? profile.padding.values().next().value : 1;
}

/* Decode a parsed file. Returns one Float32Array per channel (-1..1, before
   clamping), the number of bytes each frame used and the coding profile.
   Only the channels listed in `want` are synthesized; every frame is fully
   parsed and checked. */
function decode(file, want) {
  const cfg = file.config;
  transformTables(cfg.power);
  const blocks = cfg.blocks.map(newBlock);
  const channels = blocks.flatMap(b => b.channels);
  const wanted = want || channels.map((_, i) => i);
  const total = file.superframes * cfg.superframeSamples;
  const out = channels.map((_, i) => wanted.includes(i) ? new Float32Array(total) : null);
  const tmp = { out: new Float64Array(256), work: new Float64Array(256) };
  const frameBytes = new Uint16Array(file.superframes * cfg.framesPerSuperframe);
  const profile = newProfile();
  const bytes = file.bytes;
  let pos = 0;
  for (let s = 0; s < file.superframes; s++) {
    const start = file.data.offset + s * cfg.superframeBytes;
    const br = new Reader(bytes, start, start + cfg.superframeBytes);
    for (let f = 0; f < cfg.framesPerSuperframe; f++) {
      const before = br.pos;
      for (const blk of blocks) {
        unpackBlock(br, cfg, blk, f);
        addToProfile(profile, blk);
      }
      frameBytes[s * cfg.framesPerSuperframe + f] = (br.pos - before) >> 3;
      profile.maxFrame = Math.max(profile.maxFrame, frameBytes[s * cfg.framesPerSuperframe + f]);
      let c = 0;
      for (const blk of blocks) {
        const need = blk.channels.some((_, i) => out[c + i]);
        if (need) synthesize(cfg, blk, tmp);
        for (const ch of blk.channels) {
          const o = out[c++];
          if (o) for (let i = 0; i < cfg.frameSamples; i++) o[pos + i] = ch.pcm[i] / 32768;
        }
      }
      pos += cfg.frameSamples;
    }
    for (let p = br.pos >> 3; p < start + cfg.superframeBytes; p++) profile.padding.add(bytes[p]);
  }
  return { channels: out, frameBytes, profile };
}


