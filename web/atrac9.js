/* Some symbols have no code. The codebooks assume a unit's peak is at least
   half its scale, so small-valued groups, all-zero ones included, are
   missing from several books. Map each such symbol to the closest symbol that
   has a code. (Digital silence then becomes a value of about 1e-9 of full
   scale, far below one 16-bit step.) */
function nearestCodable(cb) {
  if (cb.near) return cb.near;
  const n = cb.bits.length, vals = [];
  for (let s = 0; s < n; s++) {
    const v = [];
    for (let j = 0, x = s; j < cb.vc; j++, x >>= cb.vb) v.push(signExtend(x & cb.mask, cb.vb));
    vals.push(v);
  }
  cb.near = new Int32Array(n);
  for (let s = 0; s < n; s++) {
    if (cb.bits[s]) { cb.near[s] = s; continue; }
    let best = -1, bestErr = Infinity;
    for (let t = 0; t < n; t++) {
      if (!cb.bits[t]) continue;
      let err = 0;
      for (let j = 0; j < cb.vc; j++) err += (vals[s][j] - vals[t][j]) ** 2;
      err = err * 64 + cb.bits[t];               // ties: the shorter code
      if (err < bestErr) { bestErr = err; best = t; }
    }
    cb.near[s] = best;
  }
  return cb.near;
}

