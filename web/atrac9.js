// Quantize one unit at precision p (1..15). Returns the coded bits and the
// squared error; with `store` the values are kept for writing.
function quantizeUnit(ch, unit, p, cfg, store) {
  const { spectrum } = codebooks();
  const start = UNIT_START[unit], end = UNIT_START[unit + 1];
  const scale = 2 ** (ch.sf[unit] - 15), step = STEP[p], lim = (1 << p) - 1;
  const q = store ? ch.q : ch.scratchQ;
  for (let k = start; k < end; k++) {
    let c = Math.round(ch.x[k] / scale / step);
    q[k] = c > lim ? lim : c < -lim ? -lim : c;
  }
  let bits = 0;
  if (p + 1 <= (cfg.high ? 1 : 7)) {
    const cb = spectrum[ch.set[unit]][p + 1][UNIT_BOOK[unit]], near = nearestCodable(cb);
    for (let k = start; k < end; k += cb.vc) {
      let sym = 0;
      for (let j = 0; j < cb.vc; j++) sym |= (q[k + j] & cb.mask) << (j * cb.vb);
      if (!cb.bits[sym]) {
        sym = near[sym];
        for (let j = 0, v = sym; j < cb.vc; j++, v >>= cb.vb) q[k + j] = signExtend(v & cb.mask, cb.vb);
      }
      bits += cb.bits[sym];
    }
  } else {
    bits = (end - start) * (p + 1);
  }
  let err = 0;
  for (let k = start; k < end; k++) { const e = ch.x[k] - q[k] * step * scale; err += e * e; }
  return [bits, err];
}

// Cheapest valid scale factor coding for a channel. Returns { bits, write }.
function planScaleFactors(blk, ch, other) {
  const { sfUnsigned, sfSigned } = codebooks();
  const sf = ch.sf, n = blk.units;
  let best = null;
  const offer = (bits, write) => { if (!best || bits < best.bits) best = { bits, write }; };

  // VLC delta offset (mode 0), both channels.
  for (let w = 0; w < 8; w++) {
    const weights = SF_WEIGHTS[w];
    let lo = 99, hi = -99;
    for (let i = 0; i < n; i++) { lo = Math.min(lo, sf[i] + weights[i]); hi = Math.max(hi, sf[i] + weights[i]); }
    const base = Math.min(lo, 31);
    if (base < 0) continue;
    for (let len = 3; len <= 6; len++) {
      if (hi - base >= 1 << len) continue;
      const cb = sfUnsigned[len];
      let bits = 2 + 3 + 5 + 2 + len, ok = true;
      for (let i = 1; i < n && ok; i++) {
        const d = ((sf[i] + weights[i]) - (sf[i - 1] + weights[i - 1])) & cb.mask;
        if (!cb.bits[d]) ok = false; else bits += cb.bits[d];
      }
      if (!ok) continue;
      offer(bits, wr => {
        wr.write(0, 2); wr.write(w, 3); wr.write(base, 5); wr.write(len - 3, 2);
        wr.write(sf[0] + weights[0] - base, len);
        for (let i = 1; i < n; i++) {
          const d = ((sf[i] + weights[i]) - (sf[i - 1] + weights[i - 1])) & cb.mask;
          wr.write(cb.codes[d], cb.bits[d]);
        }
      });
    }
  }
  if (ch.index === 0) {
    // Fixed-length offset (mode 1).
    let lo = 31, hi = 0;
    for (let i = 0; i < n; i++) { lo = Math.min(lo, sf[i]); hi = Math.max(hi, sf[i]); }
    for (let len = 2; len <= 5; len++) {
      const base = len < 5 ? lo : 0;
      if (hi - base >= 1 << len) continue;
      offer(2 + 2 + (len < 5 ? 5 : 0) + n * len, wr => {
        wr.write(1, 2); wr.write(len - 2, 2);
        if (len < 5) wr.write(base, 5);
        for (let i = 0; i < n; i++) wr.write(sf[i] - base, len);
      });
    }
  } else {
    // Distance to the first channel (mode 1 for the second channel).
    for (let len = 2; len <= 5; len++) {
      const cb = sfSigned[len], half = 1 << (len - 1);
      let bits = 2 + 2, ok = true;
      for (let i = 0; i < n && ok; i++) {
        const d = sf[i] - other.sf[i];
        if (d < -half || d >= half || !cb.bits[d & cb.mask]) ok = false; else bits += cb.bits[d & cb.mask];
      }
      if (!ok) continue;
      offer(bits, wr => {
        wr.write(1, 2); wr.write(len - 2, 2);
        for (let i = 0; i < n; i++) { const s = (sf[i] - other.sf[i]) & cb.mask; wr.write(cb.codes[s], cb.bits[s]); }
      });
    }
  }
  return best;
}

function setupEncodeBlock(cfg, blk, bandCount, reuse) {
  blk.bandCount = bandCount;
  blk.units = BAND_UNITS[bandCount];
  blk.stereoUnits = blk.units;
  blk.extUnit = blk.units;
  blk.reuse = reuse;
  for (const ch of blk.channels) {
    ch.coded = blk.units;
    ch.sf.fill(0);
    for (let i = 0; i < blk.units; i++) {
      let peak = 0;
      for (let k = UNIT_START[i]; k < UNIT_START[i + 1]; k++) peak = Math.max(peak, Math.abs(ch.x[k]));
      ch.sf[i] = scaleFactorFor(peak);
    }
    codebookSets(cfg, ch, blk.units);
    // The precision mask of gradient modes 1-3 (as the decoder derives it).
    ch.mask = new Int32Array(blk.units);
    for (let i = 1; i < blk.units; i++) {
      const d = ch.sf[i] - ch.sf[i - 1];
      if (d > 1) ch.mask[i] += Math.min(d - 1, 5);
      else if (d < -1) ch.mask[i - 1] += Math.min(-d - 1, 5);
    }
    ch.memoBits = new Int32Array(32 * 16).fill(-1);
    ch.memoErr = new Float64Array(32 * 16);
  }
  for (const ch of blk.channels) ch.sfPlan = planScaleFactors(blk, ch, blk.channels[0]);
}

// Precision of a unit under gradient mode 3, exactly as the decoder derives it.
function unitPrecision(ch, unit, g, boundary) {
  let p = ch.sf[unit] + ch.mask[unit] - g[unit];
  if (p > 0) p >>= 2;
  return Math.max(p, 1) + (unit < boundary ? 1 : 0);
}

function headerBits(ctx, blk) {
  if (blk.type === LFE) return 2 + 10 + 4 * ((ctx.lfeReuse ? 8 : 4) + 1);
  let bits = 2;
  if (!blk.reuse) bits += 4 + (blk.type === STEREO ? 4 : 0) + 1;
  bits += 2 + 5 + 5 + 4;                         // gradient (mode 3)
  if (blk.type === STEREO) bits += 2;            // primary channel, no joint signs
  return bits + 1;                               // no extension data
}

// Coded size of a block (whole bytes) and its squared error, for gradient g;
// null if a unit would need more than the allowed precision.
function blockCost(ctx, blk, g, boundary) {
  const cfg = ctx.cfg;
  let bits = headerBits(ctx, blk), err = 0;
  if (blk.type !== LFE) {
    for (const ch of blk.channels) {
      bits += ch.sfPlan.bits;
      for (let i = 0; i < blk.units; i++) {
        const p = unitPrecision(ch, i, g, boundary), key = i * 16 + p;
        if (p > ctx.maxPrecision) return null;
        if (ch.memoBits[key] < 0) {
          const [b, e] = quantizeUnit(ch, i, p, cfg, false);
          ch.memoBits[key] = b;
          ch.memoErr[key] = e;
        }
        bits += ch.memoBits[key];
        err += ch.memoErr[key];
      }
    }
  }
  return [Math.ceil(bits / 8) * 8, err];
}

function writeBlock(wr, ctx, blk, frameIndex, plan, g) {
  const cfg = ctx.cfg;
  wr.write(frameIndex ? 1 : 0, 1);
  if (blk.type === LFE) {
    // Silent, coded as the system file codes its LFE (Sony's: reused
    // parameters, precision 8).
    wr.write(ctx.lfeReuse, 1);
    wr.write(0, 10);
    wr.write(0, 4 * ((ctx.lfeReuse ? 8 : 4) + 1));
    wr.align();
    return;
  }
  wr.write(blk.reuse ? 1 : 0, 1);
  const minBands = cfg.high ? 1 : 3;
  if (!blk.reuse) {
    wr.write(blk.bandCount - minBands, 4);
    if (blk.type === STEREO) wr.write(blk.bandCount - minBands, 4);
    wr.write(0, 1);
  }
  const boundary = Math.min(plan.boundary, blk.units);
  wr.write(3, 2); wr.write(plan.start, 5); wr.write(plan.value, 5); wr.write(boundary, 4);
  if (blk.type === STEREO) { wr.write(0, 1); wr.write(0, 1); }
  wr.write(0, 1);
  const { spectrum } = codebooks();
  for (const ch of blk.channels) {
    ch.sfPlan.write(wr);
    for (let i = 0; i < blk.units; i++) {
      const p = unitPrecision(ch, i, g, boundary), start = UNIT_START[i], end = UNIT_START[i + 1];
      quantizeUnit(ch, i, p, cfg, true);
      if (p + 1 <= (cfg.high ? 1 : 7)) {
        const cb = spectrum[ch.set[i]][p + 1][UNIT_BOOK[i]];
        for (let k = start; k < end; k += cb.vc) {
          let sym = 0;
          for (let j = 0; j < cb.vc; j++) sym |= (ch.q[k + j] & cb.mask) << (j * cb.vb);
          wr.write(cb.codes[sym], cb.bits[sym]);
        }
      } else {
        for (let k = start; k < end; k++) wr.write(ch.q[k] & ((1 << (p + 1)) - 1), p + 1);
      }
    }
  }
  wr.align();
}

// Smallest band count (up to maxBands) whose units cover every non-silent bin.
function bandsFor(cfg, chans, maxBands) {
  let last = -1;
  for (const x of chans) for (let k = 255; k > last; k--) if (Math.abs(x[k]) >= 2 ** -15) { last = k; break; }
  let b = cfg.high ? 1 : 3;
  while (b < maxBands && UNIT_START[BAND_UNITS[b]] <= last) b++;
  return b;
}

/* Encode PCM into an .at9 laid out like `stock` (same ATRAC9 config, so the
   same channel layout, rate and bitrate). `left`/`right` are Float32Arrays at
   the stock sample rate in -1..1; the first block carries them and every
   other block is silent. `intro` is how many samples play once before the
   part that loops (0: all of it loops). Returns { bytes, samples (of the
   music), loop, snr, worst } and throws At9Error if the result fails the
   decode check. `progress(fraction)` is optional and may return a promise
   (to yield to the UI). */
async function encode(stockBytes, left, right, progress, intro = 0) {
  const stock = parseFile(stockBytes);
  const cfg = stock.config;
  if (cfg.high) fail("this console's music uses a high sample rate the encoder does not support");
  if (cfg.power !== 8) fail("unsupported ATRAC9 frame size");
  transformTables(cfg.power);
  const song = Math.min(left.length, right.length);
  if (!song) fail("the music is empty");

  /* Looping files get the layout of the console's own music: the loop starts
     inside the audio and more audio follows its end (Sony's music loops from
     6-128 s in, with 0.1-42 s after the loop). After the music comes the
     start of the looping part again, so the file goes on past the loop end
     exactly as playback does. With no intro, the loop starts a little into
     the music and the repeat covers that too, so all of it still loops with
     no seam. */
  if (!(intro >= 0 && intro <= song - 1)) intro = 0;
  const loop = stock.loop ? loopLayout(song, cfg.rate, Math.round(intro)) : null;
  if (loop) {
    left = withTail(left, song, loop.from, loop.tail);
    right = withTail(right, song, loop.from, loop.tail);
  }
  const n = song + (loop ? loop.tail : 0);

  // What the system file uses bounds what the encoder writes.
  const profile = stock.superframes ? decode(stock, []).profile : DEFAULT_PROFILE;
  if (!(profile.modes & 8)) fail("the system sound is coded in a way this encoder does not support");
  const ctx = {
    cfg, profile,
    maxBands: Math.min(profile.maxBands, MAX_BANDS[cfg.sri]),
    maxPrecision: Math.min(profile.maxPrecision, MAX_PRECISION),
    lfeReuse: profile.lfeReuse & 2 ? 1 : 0,
    padding: paddingByte(profile),
  };

  const N = cfg.frameSamples, delay = Math.max(N, stock.fact ? stock.fact[2] : 0);
  const frames = Math.ceil((delay + n) / N);
  const superframes = Math.ceil(frames / cfg.framesPerSuperframe);
  const data = new Uint8Array(superframes * cfg.superframeBytes);

  // Input as the decoder will see it: `delay` zeros, then the music, at the
  // decoder's 16-bit scale and clipped to full scale like its output. Mono
  // layouts get the mid signal.
  const sources = [];
  if (cfg.blocks[0] === STEREO) sources.push(left, right);
  else if (cfg.blocks.length > 1 && cfg.blocks[1] === MONO) sources.push(left, null, right);
  else sources.push(Float32Array.from({ length: n }, (_, i) => (left[i] + right[i]) / 2));
  const sample = (src, t) => (src && t >= delay && t < delay + n ? Math.max(-1, Math.min(1, src[t - delay])) * 32768 : 0);

  // One set of block states per frame position, so a whole superframe can be
  // planned before it is written.
  const states = Array.from({ length: cfg.framesPerSuperframe }, () => {
    const blocks = cfg.blocks.map(newBlock);
    blocks.flatMap(b => b.channels).forEach((ch, i) => {
      ch.src = sources[i] || null;
      ch.x = new Float64Array(256);
      ch.scratchQ = new Int32Array(256);
    });
    return blocks;
  });
  const win = windows[cfg.power].mdct, z = new Float64Array(2 * N), u = new Float64Array(N), work = new Float64Array(N);
  const forward = (ch, f) => {
    if (!ch.src) { ch.x.fill(0); return; }
    const s0 = f * N;
    for (let i = 0; i < 2 * N; i++) z[i] = sample(ch.src, s0 + i) * (i < N ? win[i] : win[2 * N - 1 - i]);
    const h = N >> 1;
    for (let k = 0; k < h; k++) u[k] = -z[3 * h - 1 - k] - z[3 * h + k];
    for (let k = h; k < N; k++) u[k] = z[k - h] - z[3 * h - 1 - k];
    dct4(cfg.power, u, ch.x, work);
    for (let k = 0; k < N; k++) ch.x[k] *= 2 / N;
  };
  const audible = blk => blk.type !== LFE && blk.channels.some(c => c.src);
  const budget = cfg.superframeBytes * 8, cap = Math.floor(cfg.frameBytes * FRAME_CAP) * 8;
  const fps = cfg.framesPerSuperframe;

  for (let s = 0; s < superframes; s++) {
    for (let fi = 0; fi < fps; fi++) {
      for (const blk of states[fi]) for (const ch of blk.channels) forward(ch, s * fps + fi);
    }
    let choice = null;
    for (let maxBands = ctx.maxBands; !choice; maxBands--) {
      if (maxBands < (cfg.high ? 1 : 3)) fail("the console's ATRAC9 bitrate is too low for this encoder");
      for (let fi = 0; fi < fps; fi++) {
        states[fi].forEach((blk, bi) => {
          if (blk.type === LFE) return;
          const bands = audible(blk) ? bandsFor(cfg, blk.channels.map(c => c.x), maxBands) : (cfg.high ? 1 : 3);
          setupEncodeBlock(cfg, blk, bands, fi > 0 && states[fi - 1][bi].bandCount === bands);
        });
      }
      choice = allocate(ctx, states, audible, budget, cap);
    }

    const wr = new Writer(data, s * cfg.superframeBytes);
    for (let fi = 0; fi < fps; fi++) {
      const start = wr.pos, c = CANDIDATES[choice[fi]];
      for (const blk of states[fi]) {
        if (audible(blk)) writeBlock(wr, ctx, blk, fi, c, c.g);
        else writeBlock(wr, ctx, blk, fi, SILENT_PLAN, SILENT_GRADIENT);
      }
      if (wr.pos - start > cap) fail("internal error: frame over its size limit");
    }
    if (wr.pos > (s + 1) * budget) fail("internal error: superframe over budget");
    // Unused space at the end of the superframe, filled as the system file does.
    data.fill(ctx.padding, wr.pos >> 3, (s + 1) * cfg.superframeBytes);
    if (progress && s % 64 === 0) await progress(s / superframes);
  }

  const bytes = buildFile(stock, data, n, delay, loop);
  const check = verify(bytes, sources, delay, n, stock, profile);
  return { bytes, samples: song, loop, snr: check.snr, worst: check.worst };
}

const LOOP_START = 2;            // seconds into the song where the loop starts
const LOOP_AFTER = 1;            // seconds of audio after the loop end
const LOOP_TAIL = LOOP_START + LOOP_AFTER;

// Loop points (inclusive, in samples after the encoder delay) for music of
// `song` samples whose first `intro` samples play once, and what follows the
// music in the file: `tail` samples copied from `from`.
function loopLayout(song, rate, intro) {
  if (intro > 0) {
    const after = Math.min(LOOP_AFTER * rate, Math.floor((song - intro) / 4));
    return { start: intro, end: song - 1, from: intro, tail: after };
  }
  const start = Math.min(LOOP_START * rate, Math.floor(song / 4));
  const after = Math.min(LOOP_AFTER * rate, Math.floor(song / 4));
  return { start, end: song + start - 1, from: 0, tail: start + after };
}

function withTail(x, song, from, tail) {
  const out = new Float32Array(song + tail);
  out.set(x.subarray(0, song));
  out.set(x.subarray(from, from + tail), song);
  return out;
}

/* Pick one allocation (index into CANDIDATES) per frame: the least total
   squared error with every frame within `cap` and the superframe within
   `budget`. Returns null if even the smallest allocations do not fit. */
function allocate(ctx, states, audible, budget, cap) {
  const costs = states.map(blocks => {
    let fixedBits = 0;
    for (const blk of blocks) if (!audible(blk)) fixedBits += blockCost(ctx, blk, SILENT_GRADIENT, 0)[0];
    return CANDIDATES.map(c => {
      let bits = fixedBits, err = 0;
      for (const blk of blocks) {
        if (!audible(blk)) continue;
        const cost = blockCost(ctx, blk, c.g, c.boundary);
        if (!cost) return null;
        bits += cost[0];
        err += cost[1];
      }
      return bits <= cap ? [bits, err] : null;
    });
  });
  const pick = lambda => costs.map(list => {
    let best = -1, score = Infinity;
    list.forEach((c, i) => {
      if (!c) return;
      const v = c[1] + lambda * c[0];
      if (v < score || (v === score && c[0] < list[best][0])) { score = v; best = i; }
    });
    return best;
  });
  const total = choice => choice.reduce((sum, i, f) => sum + (i < 0 ? Infinity : costs[f][i][0]), 0);
  let choice = pick(0);
  if (total(choice) <= budget) return choice;
  // Smallest allocation per frame: fewest bits, then least error.
  const smallest = costs.map(list => {
    let best = -1;
    list.forEach((c, i) => { if (c && (best < 0 || c[0] < list[best][0] || (c[0] === list[best][0] && c[1] < list[best][1]))) best = i; });
    return best;
  });
  if (total(smallest) > budget) return null;
  let lo = -12, hi = 12;
  for (let k = 0; k < 48; k++) {
    const mid = (lo + hi) / 2;
    if (total(pick(10 ** mid)) <= budget) hi = mid; else lo = mid;
  }
  choice = pick(10 ** hi);
  return total(choice) <= budget ? choice : smallest;
}

function buildFile(stock, data, samples, delay, loop) {
  const chunks = [];
  for (const c of stock.chunks) {
    if (c.id === "fmt ") chunks.push(["fmt ", c.body]);
    else if (c.id === "fact") {
      const body = new Uint8Array(c.body.length);
      body.set(c.body);
      const dv = new DataView(body.buffer);
      dv.setUint32(0, samples, true);
      if (body.length >= 12) { dv.setUint32(4, delay, true); dv.setUint32(8, delay, true); }
      chunks.push(["fact", body]);
    } else if (c.id === "smpl" && c.body.length >= 60) {
      const body = new Uint8Array(c.body.length);
      body.set(c.body);
      const dv = new DataView(body.buffer);
      dv.setUint32(44, loop ? loop.start : 0, true);
      dv.setUint32(48, loop ? loop.end : samples - 1, true);
      chunks.push(["smpl", body]);
    } else if (c.id === "data") {
      chunks.push(["data", data]);
    }
  }
  if (!chunks.some(c => c[0] === "fact")) {
    const body = new Uint8Array(12), dv = new DataView(body.buffer);
    dv.setUint32(0, samples, true); dv.setUint32(4, delay, true); dv.setUint32(8, delay, true);
    chunks.splice(1, 0, ["fact", body]);
  }
  let size = 12;
  for (const [, body] of chunks) size += 8 + body.length + (body.length & 1);
  const out = new Uint8Array(size), dv = new DataView(out.buffer);
  out.set([0x52, 0x49, 0x46, 0x46]);
  dv.setUint32(4, size - 8, true);
  out.set([0x57, 0x41, 0x56, 0x45], 8);
  let p = 12;
  for (const [id, body] of chunks) {
    for (let i = 0; i < 4; i++) out[p + i] = id.charCodeAt(i);
    dv.setUint32(p + 4, body.length, true);
    out.set(body, p + 8);
    p += 8 + body.length + (body.length & 1);
  }
  return out;
}

/* Decode the encoded file and compare it with the input, overall and in
   every 1024-sample segment, so one damaged frame cannot hide in a long track.
   A frame's transform spans 512 samples, so coding noise in segment k comes
   only from sound in segments k-1..k+1: the noise of segments k-1..k+1 is
   compared with the sound of k-2..k+2, and a segment whose neighbourhood is
   silent must stay silent. Channels without a source must decode to silence. */
function verify(bytes, sources, delay, n, stock, stockProfile) {
  const file = parseFile(bytes);
  const { channels, profile } = decode(file);
  const why = fitsProfile(profile, stockProfile, stock.config.frameBytes);
  if (why) fail(`internal error: the encoded music ${why}`);
  const SEG = 1024, segs = Math.ceil(n / SEG), used = sources.filter(Boolean).length;
  const sig = new Float64Array(segs), err = new Float64Array(segs);
  channels.forEach((out, i) => {
    const src = sources[i];
    if (!src) {
      for (let t = 0; t < out.length; t++) if (Math.abs(out[t]) > SILENCE) fail("a silent channel decoded to sound");
      return;
    }
    for (let t = 0; t < n; t++) {
      const a = Math.max(-1, Math.min(1, src[t])), e = out[t + delay] - a;
      sig[(t / SEG) | 0] += a * a;
      err[(t / SEG) | 0] += e * e;
    }
  });
  const around = (arr, k, r) => {
    let sum = 0;
    for (let j = Math.max(0, k - r); j <= Math.min(segs - 1, k + r); j++) sum += arr[j];
    return sum;
  };
  const samples = (k, r) => (Math.min(n, (k + r + 1) * SEG) - Math.max(0, (k - r) * SEG)) * used;
  let signal = 0, noise = 0, worst = 99;
  for (let k = 0; k < segs; k++) {
    signal += sig[k];
    noise += err[k];
    if (around(sig, k, 1) / samples(k, 1) <= QUIET ** 2) {
      if (err[k] / samples(k, 0) > QUIET ** 2) fail("a quiet passage decoded with audible noise");
    }
    const s5 = around(sig, k, 2);
    if (s5 / samples(k, 2) > QUIET ** 2) worst = Math.min(worst, 10 * Math.log10(s5 / Math.max(around(err, k, 1), 1e-30)));
  }
  // A silent input has no meaningful SNR; the quiet-passage check covers it.
  const snr = noise && signal / (n * used) > QUIET ** 2 ? 10 * Math.log10(signal / noise) : 99;
  if (!(snr >= MIN_SNR) || !(worst >= MIN_SEGMENT_SNR)) {
    fail(`the encoded music does not match the input closely enough (${snr.toFixed(1)} dB overall, ${worst.toFixed(1)} dB worst passage)`);
  }
  return { snr, worst };
}

// Loudness (RMS, -1..1 scale) of a standard stereo downmix of a parsed file.
function downmixRms(file) {
  const cfg = file.config, { channels } = decode(file);
  const [l, r] = channels;
  if (cfg.cci === 0) return rms([l]);
  if (!r) return rms([l]);
  const c = cfg.channels >= 6 ? channels[2] : null;
  const sl = cfg.channels >= 6 ? channels[4] : null, sr = cfg.channels >= 6 ? channels[5] : null;
  let sum = 0;
  const n = l.length, k = Math.SQRT1_2;
  for (let t = 0; t < n; t++) {
    const a = l[t] + (c ? k * c[t] + k * sl[t] : 0), b = r[t] + (c ? k * c[t] + k * sr[t] : 0);
    sum += a * a + b * b;
  }
  return Math.sqrt(sum / (2 * n));
}

function rms(chs) {
  let sum = 0, n = 0;
  for (const x of chs) for (let t = 0; t < x.length; t++) { sum += x[t] * x[t]; n++; }
  return n ? Math.sqrt(sum / n) : 0;
}

