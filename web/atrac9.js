let books = null;

function book(t) {
  if (!t) return null;
  const [vc, vcp, vb, maxBits, bitStr, codeStr] = t;
  const n = bitStr.length;
  const bits = new Uint8Array(n), codes = new Uint16Array(n);
  const lookup = new Int16Array(1 << maxBits).fill(-1);
  for (let s = 0; s < n; s++) {
    bits[s] = parseInt(bitStr[s], 20);
    codes[s] = parseInt(codeStr.substr(s * 3, 3), 16);
    if (!bits[s]) continue;
    const shift = maxBits - bits[s];
    lookup.fill(s, codes[s] << shift, (codes[s] + 1) << shift);
  }
  return { vc, vcp, vb, maxBits, bits, codes, lookup, mask: (1 << vb) - 1 };
}

function codebooks() {
  if (!books) {
    books = {
      sfUnsigned: SF_UNSIGNED.map(book),
      sfSigned: SF_SIGNED.map(book),
      spectrum: SPECTRUM.map(set => set.map(row => row.map(book))),
    };
  }
  return books;
}

